<script setup>
import { computed, ref } from 'vue';
const exporting = ref(false);
const exportError = ref('');
// Report Center: ONE row set drives the on-screen table, the totals, the CSV, XLSX and the printable/PDF view,
// so all outputs always match. Data = authorised hrBootstrap records only. PDF = browser print (real, selectable text).
const props = defineProps({
  employees: { type: Array, default: () => [] },
  records: { type: Object, default: () => ({}) },
  teamLeave: { type: Array, default: () => [] },
  user: { type: Object, default: () => ({}) }
});
const MYT = 'Asia/Kuala_Lumpur';
const kind = ref('headcount');
const company = ref('all');
const department = ref('all');
const from = ref('');
const to = ref('');
const companies = computed(() => props.records.companies || []);
const departments = computed(() => (props.records.departments || []).filter((d) => company.value === 'all' || String(d.companyId) === company.value));
const cName = (id) => companies.value.find((c) => String(c.id) === String(id))?.title || id || 'Unassigned';
const dName = (id) => (props.records.departments || []).find((d) => String(d.id) === String(id))?.title || id || 'Unassigned';
const staff = computed(() => props.employees.filter((e) => (company.value === 'all' || String(e.companyId || e.company || '') === company.value) && (department.value === 'all' || String(e.departmentId || e.department || '') === department.value)));
const names = computed(() => new Set(staff.value.map((e) => e.name)));
const inRange = (d) => { const s = String(d || '').slice(0, 10); return (!from.value || s >= from.value) && (!to.value || s <= to.value); };
const myr = (n) => Number(n || 0).toFixed(2);
const DEFS = {
  headcount: { title: 'Headcount list', cols: ['Employee', 'Employee no', 'Company', 'Department', 'Job title', 'Manager', 'Status'], rows: () => staff.value.map((e) => [e.name, e.employeeNo || '', cName(e.companyId || e.company), dName(e.departmentId || e.department), e.jobTitle || '', e.manager || '', e.status || '']) },
  leave: { title: 'Approved leave', cols: ['Employee', 'Leave type', 'Start', 'End'], rows: () => props.teamLeave.filter((l) => names.value.has(l.employee) && (inRange(l.start) || inRange(l.end))).map((l) => [l.employee, l.type, l.start, l.end]) },
  claims: { title: 'Claims (requested amounts, RM)', cols: ['Employee', 'Category', 'Date', 'Status', 'Amount (RM)'], rows: () => (props.records.claims || []).filter((c) => (!c.employee || names.value.has(c.employee)) && inRange(c.date)).map((c) => [c.employee || '', c.category || 'Unspecified', c.date || '', c.status || '', myr(c.amount)]) },
  training: { title: 'Training and certification expiry', cols: ['Employee', 'Course', 'Training date', 'Certificate expiry', 'Status'], rows: () => (props.records.training || []).filter((t) => (!t.employee || names.value.has(t.employee))).map((t) => [t.employee || '', t.title || '', t.date || '', t.expiry || '', t.status || '']) },
  appraisals: { title: 'Appraisal final ratings', cols: ['Employee', 'Status', 'Final rating'], rows: () => (props.records.appraisals || []).filter((a) => !a.employee || names.value.has(a.employee)).map((a) => [a.employee || '', a.status || '', Number.isFinite(Number(a.finalRating)) && Number(a.finalRating) > 0 ? a.finalRating : 'Not rated']) }
};
const def = computed(() => DEFS[kind.value]);
const rows = computed(() => def.value.rows());
const total = computed(() => (kind.value === 'claims' ? rows.value.reduce((s, r) => s + Number(r[4]), 0) : null));
const scopeText = computed(() => `Company: ${company.value === 'all' ? 'All authorised' : cName(company.value)}; Department: ${department.value === 'all' ? 'All' : dName(department.value)}; Period: ${from.value || 'start'} to ${to.value || 'latest'}`);
const stamp = () => new Intl.DateTimeFormat('en-GB', { timeZone: MYT, dateStyle: 'medium', timeStyle: 'short' }).format(new Date()) + ' MYT';
const generated = ref(stamp());
const csvCell = (x) => '"' + String(x ?? '').replace(/^[=+@\-\t\r]/, "'$&").replaceAll('"', '""') + '"';
function exportCsv() {
  generated.value = stamp();
  const meta = [['PplosHR Report', def.value.title], ['Scope', scopeText.value], ['Generated', generated.value], ['Generated by', props.user?.name || ''], ['Rows', rows.value.length], []];
  if (total.value !== null) meta.splice(5, 0, ['Total amount (RM)', myr(total.value)]);
  const table = [...meta, def.value.cols, ...rows.value];
  const url = URL.createObjectURL(new Blob(['\uFEFF' + table.map((r) => r.map(csvCell).join(',')).join('\r\n')], { type: 'text/csv;charset=utf-8' }));
  const a = document.createElement('a'); a.href = url; a.download = `PplosHR-${kind.value}-${new Date().toISOString().slice(0, 10)}.csv`; a.click(); URL.revokeObjectURL(url);
}
async function exportXlsx() {
  if (exporting.value) return;
  exporting.value = true; exportError.value = '';
  try {
  const module = await import('xlsx-js-style');
  const XLSX = module.default || module;
  generated.value = stamp();
  const meta = [['PplosHR Report', def.value.title], ['Scope', scopeText.value], ['Generated', generated.value], ['Generated by', props.user?.name || ''], ['Rows', rows.value.length], []];
  if (total.value !== null) meta.splice(5, 0, ['Total amount (RM)', myr(total.value)]);
  const table = [...meta, def.value.cols, ...rows.value];
  const ws = XLSX.utils.aoa_to_sheet(table);
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, def.value.title.slice(0, 31));
  XLSX.writeFile(wb, `PplosHR-${kind.value}-${new Date().toISOString().slice(0, 10)}.xlsx`);
  } catch (error) { exportError.value = 'Could not export Excel. Please try again.'; }
  finally { exporting.value = false; }
}
function printPdf() {
  generated.value = stamp();
  document.body.classList.add('printing-report');
  const done = () => { document.body.classList.remove('printing-report'); window.removeEventListener('afterprint', done); };
  window.addEventListener('afterprint', done);
  setTimeout(() => window.print(), 50);
}
</script>

<template>
  <section class="rp-card" aria-labelledby="rpTitle">
    <p v-if="exportError" class="alert alert-danger" role="alert">{{ exportError }}</p>
    <div class="rp-controls no-print">
      <div><h6 id="rpTitle">Report Center</h6><p class="rp-note">CSV, XLSX and PDF export the exact rows shown below, within your authorised scope.</p></div>
      <div class="rp-filters">
        <label>Report <select v-model="kind" class="form-select form-select-sm"><option value="headcount">Headcount</option><option value="leave">Approved leave</option><option value="claims">Claims</option><option value="training">Training / certificates</option><option value="appraisals">Appraisals</option></select></label>
        <label>Company <select v-model="company" class="form-select form-select-sm" @change="department = 'all'"><option value="all">All</option><option v-for="c in companies" :key="c.id" :value="String(c.id)">{{ c.title }}</option></select></label>
        <label>Department <select v-model="department" class="form-select form-select-sm"><option value="all">All</option><option v-for="d in departments" :key="d.id" :value="String(d.id)">{{ d.title }}</option></select></label>
        <label v-if="['leave', 'claims'].includes(kind)">From <input v-model="from" type="date" class="form-control form-control-sm" /></label>
        <label v-if="['leave', 'claims'].includes(kind)">To <input v-model="to" type="date" class="form-control form-control-sm" /></label>
        <button type="button" class="btn btn-sm btn-outline-secondary" @click="exportCsv">Download CSV</button>
        <button type="button" class="btn btn-sm btn-outline-success" :disabled="exporting" :aria-busy="exporting" @click="exportXlsx">Download XLSX</button>
        <button type="button" class="btn btn-sm btn-dark" @click="printPdf">Print / Save PDF</button>
      </div>
    </div>
    <div id="reportPrintArea" class="rp-print">
      <header class="rp-header"><strong>PplosHR</strong> - {{ def.title }}<br /><small>{{ scopeText }}<br />Generated {{ generated }} by {{ user?.name || 'user' }}. Rows: {{ rows.length }}<span v-if="total !== null">. Total RM {{ myr(total) }}</span></small></header>
      <p v-if="!rows.length" class="rp-empty">No records match this scope.</p>
      <table v-else class="rp-table"><thead><tr><th v-for="c in def.cols" :key="c" scope="col">{{ c }}</th></tr></thead>
        <tbody><tr v-for="(r, i) in rows" :key="i"><td v-for="(v, j) in r" :key="j">{{ v }}</td></tr></tbody></table>
    </div>
  </section>
</template>

